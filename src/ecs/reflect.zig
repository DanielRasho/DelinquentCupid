    try testing.expectEqual(@as(?Reason, null), desc.unwalkable);
}

test "reflect - hostile struct compiles" {
    // The point of this test is that it compiles at all: `describe` must
    // never reject a type, or adding an odd field to a component would break
    // the build instead of just being uneditable.
    const Self = struct { next: ?*@This(), n: u8 };
    const Tagged = union(enum) { a: u32, b: f32 };
    const Untagged = union { a: u32, b: f32 };
    const Nested = struct {};

    const T = struct {
        one: *const u8,
        slice: []const u8,
        many: [*:0]const u8,
        opt: ?u32,
        self_ref: ?*Self,
        untagged: Untagged,
        tagged: Tagged,
        arr: [4]f32,
        vec: @Vector(4, f32),
        nothing: void,
        err: anyerror,
        nested: Nested,
    };

    const desc = describe(T);
    try testing.expectEqual(@as(usize, 12), desc.fields.len);

    const byName = struct {
        fn get(d: *const TypeDescriptor, name: []const u8) FieldDesc {
            for (d.fields) |f| {
                if (std.mem.eql(u8, f.name, name)) return f;
            }
            unreachable;
        }
    }.get;

    try testing.expectEqual(Reason.pointer_like, byName(desc, "one").kind.unsupported.reason);
    try testing.expectEqual(Reason.pointer_like, byName(desc, "slice").kind.unsupported.reason);
    try testing.expectEqual(Reason.pointer_like, byName(desc, "many").kind.unsupported.reason);
    try testing.expectEqual(Reason.optional_type, byName(desc, "opt").kind.unsupported.reason);
    // A self-referential type terminates: recursion stops at the pointer.
    try testing.expectEqual(Reason.optional_type, byName(desc, "self_ref").kind.unsupported.reason);
    try testing.expectEqual(Reason.union_type, byName(desc, "tagged").kind.unsupported.reason);
    try testing.expectEqual(Reason.array_type, byName(desc, "arr").kind.unsupported.reason);
    try testing.expectEqual(Reason.vector_type, byName(desc, "vec").kind.unsupported.reason);
    try testing.expectEqual(Reason.other, byName(desc, "nothing").kind.unsupported.reason);

    // An untagged union can't be formatted, so it gets no format thunk and
    // the caller falls back to raw bytes.
    const untagged = byName(desc, "untagged");
    try testing.expectEqual(Reason.union_type, untagged.kind.unsupported.reason);
    try testing.expectEqual(@as(?*const fn (b: []const u8, buf: []u8) []const u8, null), untagged.kind.unsupported.format);

    // ... while an optional int can.
    var v: T = undefined;
    v.opt = 42;
    const bytes = std.mem.asBytes(&v)[0..];
    const opt = byName(desc, "opt");
    var buf: [64]u8 = undefined;
    const printed = opt.kind.unsupported.format.?(opt.bytesConst(bytes), &buf);
    try testing.expect(std.mem.indexOf(u8, printed, "42") != null);

    // An empty nested struct still recurses rather than degrading.
    try testing.expectEqual(@as(usize, 0), byName(desc, "nested").kind.@"struct".fields.len);
}
