test "reflect - enum" {
    const Status = enum { READY, PLAYING, WIN, LOOSE };
    const T = struct { status: Status };
    const desc = describe(T);
    var v = T{ .status = .PLAYING };
    const bytes = std.mem.asBytes(&v)[0..];

    const f = desc.fields[0];
    const access = f.kind.@"enum";
    try testing.expect(access.is_exhaustive);
    try testing.expectEqual(@as(usize, 4), access.values.len);
    try testing.expectEqualStrings("READY", access.values[0].name);
    try testing.expectEqual(@as(i64, 3), access.values[3].value);

    try testing.expectEqual(@as(i64, 1), access.load(f.bytes(bytes)));
    try testing.expectEqualStrings("PLAYING", access.nameOf(1).?);
    try testing.expectEqual(@as(?[:0]const u8, null), access.nameOf(99));

    access.store(f.bytes(bytes), 3);
    try testing.expectEqual(Status.LOOSE, v.status);

    // A value outside the tag set is ignored rather than written.
    access.store(f.bytes(bytes), 99);
    try testing.expectEqual(Status.LOOSE, v.status);
}

