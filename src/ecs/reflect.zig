const testing = std.testing;

test "reflect - scalars" {
    const T = struct { x: f32, n: u8, flag: bool };
    const desc = describe(T);

    try testing.expectEqualStrings(@typeName(T), desc.name);
    try testing.expectEqualStrings("T", desc.short_name);
    try testing.expectEqual(@as(?Reason, null), desc.unwalkable);
    try testing.expectEqual(@as(usize, 3), desc.fields.len);

    inline for (std.meta.fields(T), 0..) |sf, i| {
        try testing.expectEqual(@offsetOf(T, sf.name), desc.fields[i].offset);
    }

    var v = T{ .x = 1.5, .n = 7, .flag = false };
    const bytes = std.mem.asBytes(&v)[0..];

    const x = desc.fields[0];
    const n = desc.fields[1];
    const flag = desc.fields[2];

    try testing.expectEqual(@as(f64, 1.5), x.kind.float.load(x.bytes(bytes)));
    try testing.expectEqual(@as(u16, 32), x.kind.float.bits);
    x.kind.float.store(x.bytes(bytes), -2.25);
    try testing.expectEqual(@as(f32, -2.25), v.x);

    try testing.expectEqual(@as(u64, 7), n.kind.uint.load(n.bytes(bytes)));
    try testing.expectEqual(@as(u64, 0), n.kind.uint.min);
    try testing.expectEqual(@as(u64, 255), n.kind.uint.max);

    // Stores saturate at the real field type's bounds rather than wrapping.
    n.kind.uint.store(n.bytes(bytes), 300);
    try testing.expectEqual(@as(u8, 255), v.n);

    try testing.expect(!flag.kind.bool.load(flag.bytes(bytes)));
    flag.kind.bool.store(flag.bytes(bytes), true);
    try testing.expect(v.flag);
}

test "reflect - signed saturation" {
    const T = struct { small: i8 };
    const desc = describe(T);
    var v = T{ .small = 0 };
    const bytes = std.mem.asBytes(&v)[0..];
    const f = desc.fields[0];

    try testing.expectEqual(@as(i64, -128), f.kind.int.min);
    try testing.expectEqual(@as(i64, 127), f.kind.int.max);

    f.kind.int.store(f.bytes(bytes), 9000);
    try testing.expectEqual(@as(i8, 127), v.small);
    f.kind.int.store(f.bytes(bytes), -9000);
    try testing.expectEqual(@as(i8, -128), v.small);
}

test "reflect - int widths" {
    const T = struct { a: i3, b: u48, c: i64, d: u64, e: u128, f: f16, g: f128 };
    const desc = describe(T);
    var v = T{ .a = 0, .b = 0, .c = 0, .d = 0, .e = 0, .f = 0, .g = 0 };
    const bytes = std.mem.asBytes(&v)[0..];

    const byName = struct {
        fn get(d: *const TypeDescriptor, name: []const u8) FieldDesc {
            for (d.fields) |f| {
                if (std.mem.eql(u8, f.name, name)) return f;
            }
            unreachable;
        }
    }.get;

    const a = byName(desc, "a");
    try testing.expectEqual(@as(i64, -4), a.kind.int.min);
    try testing.expectEqual(@as(i64, 3), a.kind.int.max);

    const b = byName(desc, "b");
    try testing.expectEqual(@as(u64, std.math.maxInt(u48)), b.kind.uint.max);

    const c = byName(desc, "c");
    c.kind.int.store(c.bytes(bytes), std.math.minInt(i64));
    try testing.expectEqual(std.math.minInt(i64), v.c);
    try testing.expectEqual(@as(i64, std.math.minInt(i64)), c.kind.int.load(c.bytes(bytes)));

    // The whole reason signed and unsigned get separate carriers: maxInt(u64)
    // has no i64 representation.
    const d = byName(desc, "d");
    d.kind.uint.store(d.bytes(bytes), std.math.maxInt(u64));
    try testing.expectEqual(std.math.maxInt(u64), v.d);
    try testing.expectEqual(@as(u64, std.math.maxInt(u64)), d.kind.uint.load(d.bytes(bytes)));

    try testing.expectEqual(Reason.too_wide, byName(desc, "e").kind.unsupported.reason);
    try testing.expectEqual(@as(u16, 16), byName(desc, "f").kind.float.bits);
    try testing.expectEqual(Reason.too_wide, byName(desc, "g").kind.unsupported.reason);
}

test "reflect - under-aligned field" {
