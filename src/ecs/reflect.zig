//! Comptime -> runtime reflection for component types.
//!
//! A component's `type` only exists at compile time; once stored, the ECS
//! knows it as an erased `@typeName` string (see `component.zig`'s
//! `IComponentStore`), and there's no way to turn that string back into a
//! `type` at runtime. That's normally the end of the road for a tool that
//! wants to *edit* a component it wasn't compiled against.
//!
//! The way around it: never try to recover the type -- capture what a tool
//! needs *while* the type is still known. `ComponentStore(T).interface()` is
//! comptime-specialised per component and is the single place an
//! `IComponentStore` is ever built, so `describe(T)` runs there and the
//! resulting descriptor rides along in the vtable. Every column in the
//! database therefore carries its own field layout, for free, for any type
//! anyone ever calls `setComponent` with -- no registration, no manifest, and
//! no constraint on which file a component is declared in.
//!
//! Descriptors are static `.rodata`: no allocator, and `describe(T)` returns
//! the *same* pointer every time (generic instantiation is memoised), so
//! descriptor identity is a usable invariant.
//!
//! Each leaf field carries comptime-generated load/store thunks rather than
//! just an offset and a bit width. That keeps every pointer cast in this
//! file, inside code the compiler generated for a known type: callers only
//! ever do bounds-checked byte-slice arithmetic. It also means odd widths
//! (`u3`, `u48`, `f16`) and explicitly under-aligned fields (`x: f32
//! align(1)`) are handled exactly, instead of being dropped by a switch over
//! the handful of widths a UI happens to know about.
//!
//! `describe` is *total*: it never fails to compile for any type that can
//! exist at runtime. That's deliberate -- a reflection layer that rejects an
//! unusual field type would turn "add a field to a component" into "break the
//! build". Anything it can't offer widgets for degrades to `.unsupported`.
//!
//! Cost: every component type ever stored drags its descriptor and thunks
//! into the binary, reachable from the vtable, so they survive even a release
//! build with the debug tools unused. That's a few hundred bytes per
//! component type. If it ever matters, `describe` can be gated on a root decl
//! and made to return an empty descriptor, which degrades the inspector to
//! listing names only.

const std = @import("std");
const assert = std.debug.assert;

/// Why a type or field has no editable representation.
pub const Reason = enum {
    /// `@offsetOf` is not meaningful for a non-byte-aligned packed field.
    packed_layout,
    not_a_struct,
    pointer_like,
    optional_type,
    union_type,
    array_type,
    vector_type,
    /// Wider than the i64/u64/f64 carriers, e.g. `u128`, `f128`.
    too_wide,
    comptime_field,
    other,
};

// ===============
// FIELD ACCESS
// ===============
// Leaf values are read and written through these thunks, generated by `Acc`
// below for the field's real type *and* its real alignment. Values travel in
// a widened carrier (i64/u64/f64) so one runtime signature covers every
// width; stores narrow back with `std.math.lossyCast`, which saturates at the
// field type's bounds rather than wrapping.

pub const BoolAccess = struct {
    load: *const fn (b: []const u8) bool,
    store: *const fn (b: []u8, v: bool) void,
};

/// Integer access widened to `Carrier`. Signed fields use `i64`, unsigned use
/// `u64` -- one carrier can't cover both, since `maxInt(u64)` doesn't fit in
/// an i64 and `minInt(i64)` doesn't fit in a u64.
pub fn IntAccess(comptime Carrier: type) type {
    return struct {
        bits: u16,
        /// The real field type's bounds, ready to hand a slider as limits.
        min: Carrier,
        max: Carrier,
        load: *const fn (b: []const u8) Carrier,
        /// Saturates at `min`/`max` instead of wrapping.
        store: *const fn (b: []u8, v: Carrier) void,
    };
}

pub const FloatAccess = struct {
    bits: u16,
    load: *const fn (b: []const u8) f64,
    store: *const fn (b: []u8, v: f64) void,
};

pub const EnumValue = struct {
    name: [:0]const u8,
    value: i64,
};

pub const EnumAccess = struct {
    tag_name: [:0]const u8,
    is_exhaustive: bool,
    values: []const EnumValue,
    /// The active tag as its integer value; compare against `values`.
    load: *const fn (b: []const u8) i64,
    /// A no-op when `v` isn't one of `values` -- an invalid tag is never
    /// written, so a dropdown can't corrupt the component.
    store: *const fn (b: []u8, v: i64) void,

    pub fn nameOf(self: EnumAccess, v: i64) ?[:0]const u8 {
        for (self.values) |ev| {
            if (ev.value == v) return ev.name;
        }
        return null;
    }
};

pub const Unsupported = struct {
    reason: Reason,
    /// Renders the live value read-only via `{any}`, or null when the type
    /// can't be formatted at all (untagged unions, pointers, `type`, ...).
    /// Callers fall back to dumping the field's raw bytes.
    format: ?*const fn (b: []const u8, buf: []u8) []const u8 = null,
};

/// What a field is, and how to touch it. Tag names mirror `std.builtin.Type`
/// so a `switch` over this reads like a switch over `@typeInfo`.
pub const FieldKind = union(enum) {
    bool: BoolAccess,
    int: IntAccess(i64),
    uint: IntAccess(u64),
    float: FloatAccess,
    @"enum": EnumAccess,
    /// Nested struct -- recurse into this descriptor against the same bytes.
    @"struct": *const TypeDescriptor,
    unsupported: Unsupported,
};

pub const FieldDesc = struct {
    /// The field's declared name, already sentinel-terminated (that's how
    /// `std.builtin.Type.StructField` stores it), so it drops straight into a
    /// C API expecting `[*:0]const u8`.
    name: [:0]const u8,
    type_name: [:0]const u8,
    offset: usize,
    size: usize,
    kind: FieldKind,

    /// This field's slice of a component's bytes. Bounds-checked, so a
    /// mismatch between a descriptor and the buffer it's applied to trips
    /// immediately rather than reading a neighbouring field.
    pub fn bytes(self: FieldDesc, component_bytes: []u8) []u8 {
        return component_bytes[self.offset..][0..self.size];
    }

    pub fn bytesConst(self: FieldDesc, component_bytes: []const u8) []const u8 {
        return component_bytes[self.offset..][0..self.size];
    }
};

pub const TypeDescriptor = struct {
    /// Exactly `@typeName(T)` -- byte-identical to the key this component is
    /// stored under in `ArchetypeTable.components`.
    name: [:0]const u8,
    /// `name` with the module path stripped: "game.components.Ball" -> "Ball".
    short_name: [:0]const u8,
    size: usize,
    alignment: usize,
    fields: []const FieldDesc,
    /// Set when the type itself couldn't be walked, in which case `fields` is
    /// empty (a packed struct) or holds one synthetic `value` field (a
    /// non-struct component).
    unwalkable: ?Reason = null,
};

// ===============
// PUBLIC API
// ===============

/// Static field layout for `T`. Allocation-free, `.rodata`, and
/// pointer-identical across every call for the same `T`.
pub fn describe(comptime T: type) *const TypeDescriptor {
    return &Described(T).descriptor;
}

/// Holds the descriptor and its field array as container-level constants, so
/// `&field_array` is a pointer to static data with program lifetime. Building
/// the array in a function that returns it *by value* matters: taking the
/// address of a `comptime var` instead would be rejected outright.
fn Described(comptime T: type) type {
    return struct {
        const field_array = buildFields(T);
        const descriptor: TypeDescriptor = .{
            .name = @typeName(T),
            .short_name = shortName(T),
            .size = @sizeOf(T),
            .alignment = @alignOf(T),
            .fields = &field_array,
            .unwalkable = unwalkable(T),
        };
    };
}

fn shortName(comptime T: type) [:0]const u8 {
    const full: [:0]const u8 = @typeName(T);
    const start = if (std.mem.lastIndexOfScalar(u8, full, '.')) |i| i + 1 else 0;
    return full[start.. :0];
}

fn unwalkable(comptime T: type) ?Reason {
    return switch (@typeInfo(T)) {
        .@"struct" => |info| if (info.layout == .@"packed") .packed_layout else null,
        else => .not_a_struct,
    };
}

fn fieldCount(comptime T: type) usize {
    return switch (@typeInfo(T)) {
        // A packed struct's fields have bit offsets, not byte offsets, and
        // `@offsetOf` is a compile error for the non-byte-aligned ones.
        .@"struct" => |info| if (info.layout == .@"packed") 0 else info.fields.len,
        // A non-struct component (`setComponent(e, @as(u32, 3))` is legal)
        // gets one synthetic field so it's still editable.
        else => 1,
    };
}

fn buildFields(comptime T: type) [fieldCount(T)]FieldDesc {
    var out: [fieldCount(T)]FieldDesc = undefined;
    switch (@typeInfo(T)) {
        .@"struct" => |info| {
            if (info.layout == .@"packed") return out;
            for (info.fields, 0..) |f, i| {
                out[i] = .{
                    .name = f.name,
                    .type_name = @typeName(f.type),
                    .offset = @offsetOf(T, f.name),
                    .size = @sizeOf(f.type),
                    .kind = if (f.is_comptime)
                        unsupportedKind(f.type, .comptime_field)
                    else
                        // `alignment` is null unless declared explicitly, and
                        // an explicit one can be *lower* than natural, so the
                        // thunks have to be built for whichever it is.
                        describeValue(f.type, f.alignment orelse @alignOf(f.type)),
                };
            }
        },
        else => out[0] = .{
            .name = "value",
            .type_name = @typeName(T),
            .offset = 0,
            .size = @sizeOf(T),
            .kind = describeValue(T, @alignOf(T)),
        },
    }
    return out;
}

fn describeValue(comptime F: type, comptime declared_align: usize) FieldKind {
    const A = @max(declared_align, 1);
    const access = Acc(F, A);

    return switch (@typeInfo(F)) {
        .bool => .{ .bool = .{ .load = access.loadBool, .store = access.storeBool } },

        .int => |info| blk: {
            if (info.bits == 0 or info.bits > 64) break :blk unsupportedKind(F, .too_wide);
            break :blk switch (info.signedness) {
                .signed => .{ .int = .{
                    .bits = info.bits,
                    .min = std.math.minInt(F),
                    .max = std.math.maxInt(F),
                    .load = access.loadInt,
                    .store = access.storeInt,
                } },
                .unsigned => .{ .uint = .{
                    .bits = info.bits,
                    .min = 0,
                    .max = std.math.maxInt(F),
                    .load = access.loadUint,
                    .store = access.storeUint,
                } },
            };
        },

        .float => |info| if (info.bits > 64)
            unsupportedKind(F, .too_wide)
        else
            .{ .float = .{ .bits = info.bits, .load = access.loadFloat, .store = access.storeFloat } },

        .@"enum" => |info| blk: {
            // A single-member enum is zero-sized: there are no bytes to point
            // a thunk at, and nothing to choose between anyway.
            if (@sizeOf(F) == 0) break :blk unsupportedKind(F, .other);
            if (!enumFitsCarrier(info.tag_type)) break :blk unsupportedKind(F, .too_wide);
            break :blk .{ .@"enum" = .{
                .tag_name = @typeName(info.tag_type),
                .is_exhaustive = info.is_exhaustive,
                .values = &EnumValues(F).array,
                .load = access.loadEnum,
                .store = access.storeEnum,
            } };
        },

        .@"struct" => |info| if (info.layout == .@"packed")
            unsupportedKind(F, .packed_layout)
        else
            .{ .@"struct" = describe(F) },

        // Recursion stops here, which is also what makes it terminate: only
        // pointers can form a cycle, and by-value nesting is always finite.
        .pointer => unsupportedKind(F, .pointer_like),
        .optional => unsupportedKind(F, .optional_type),
        .@"union" => unsupportedKind(F, .union_type),
        .array => unsupportedKind(F, .array_type),
        .vector => unsupportedKind(F, .vector_type),
        else => unsupportedKind(F, .other),
    };
}

fn unsupportedKind(comptime F: type, comptime reason: Reason) FieldKind {
    return .{ .unsupported = .{
        .reason = reason,
        .format = if (isPrintable(F)) Acc(F, @max(@alignOf(F), 1)).format else null,
    } };
}

/// True when `std.fmt` is guaranteed to accept `{any}` for `F`. Conservative
/// on purpose: a false negative costs a hex dump, while a false positive is a
/// compile error in code the caller never wrote.
fn isPrintable(comptime F: type) bool {
    return switch (@typeInfo(F)) {
        .int, .comptime_int, .float, .comptime_float, .bool, .@"enum" => true,
        .optional => |info| isPrintable(info.child),
        .array => |info| isPrintable(info.child),
        .@"struct" => |info| blk: {
            for (info.fields) |f| {
                if (!isPrintable(f.type)) break :blk false;
            }
            break :blk true;
        },
        .@"union" => |info| blk: {
            if (info.tag_type == null) break :blk false;
            for (info.fields) |f| {
                if (!isPrintable(f.type)) break :blk false;
            }
            break :blk true;
        },
        else => false,
    };
}

fn enumFitsCarrier(comptime Tag: type) bool {
    const info = @typeInfo(Tag).int;
    // An unsigned tag needs a spare bit to survive the trip through i64.
    return switch (info.signedness) {
        .signed => info.bits <= 64,
        .unsigned => info.bits <= 63,
    };
}

fn EnumValues(comptime E: type) type {
    return struct {
        const array = blk: {
            const fields = @typeInfo(E).@"enum".fields;
            var vals: [fields.len]EnumValue = undefined;
            for (fields, 0..) |ef, i| {
                vals[i] = .{ .name = ef.name, .value = ef.value };
            }
            break :blk vals;
        };
    };
}

/// The generated accessors for one field type at one alignment -- the only
/// place in the reflection path that casts a pointer. Zig analyses a
/// container's declarations lazily, so the thunks that wouldn't compile for a
/// given `F` are simply never referenced for it.
fn Acc(comptime F: type, comptime A: usize) type {
    return struct {
        fn ptr(b: []u8) *align(A) F {
            assert(b.len >= @sizeOf(F));
            return @ptrCast(@alignCast(b.ptr));
        }

        fn constPtr(b: []const u8) *align(A) const F {
            assert(b.len >= @sizeOf(F));
            return @ptrCast(@alignCast(b.ptr));
        }

        fn loadBool(b: []const u8) bool {
            return constPtr(b).*;
        }
        fn storeBool(b: []u8, v: bool) void {
            ptr(b).* = v;
        }

        fn loadInt(b: []const u8) i64 {
            return @intCast(constPtr(b).*);
        }
        fn storeInt(b: []u8, v: i64) void {
            ptr(b).* = std.math.lossyCast(F, v);
        }

        fn loadUint(b: []const u8) u64 {
            return @intCast(constPtr(b).*);
        }
        fn storeUint(b: []u8, v: u64) void {
            ptr(b).* = std.math.lossyCast(F, v);
        }

        fn loadFloat(b: []const u8) f64 {
            return @floatCast(constPtr(b).*);
        }
        fn storeFloat(b: []u8, v: f64) void {
            ptr(b).* = @floatCast(v);
        }

        fn loadEnum(b: []const u8) i64 {
            return @intFromEnum(constPtr(b).*);
        }
        fn storeEnum(b: []u8, v: i64) void {
            inline for (@typeInfo(F).@"enum".fields) |ef| {
                if (v == ef.value) {
                    ptr(b).* = @field(F, ef.name);
                    return;
                }
            }
        }

        fn format(b: []const u8, buf: []u8) []const u8 {
            return std.fmt.bufPrint(buf, "{any}", .{constPtr(b).*}) catch "<truncated>";
        }
    };
}

