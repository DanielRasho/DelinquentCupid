test "reflect - nested extern struct" {
    const Color = extern struct { r: u8, g: u8, b: u8, a: u8 };
    const T = struct { tint: Color, alpha: f32 };
    const desc = describe(T);

    var v = T{ .tint = .{ .r = 1, .g = 2, .b = 3, .a = 4 }, .alpha = 0.5 };
    const bytes = std.mem.asBytes(&v)[0..];

    const tint = desc.fields[0];
    const nested = tint.kind.@"struct";
    try testing.expectEqualStrings("Color", nested.short_name);
    try testing.expectEqual(@as(usize, 4), nested.fields.len);

    // Offsets compose: the nested descriptor is applied to the outer field's
    // byte slice, not to the whole component.
    const tint_bytes = tint.bytes(bytes);
    const blue = nested.fields[2];
    try testing.expectEqual(@as(u64, 3), blue.kind.uint.load(blue.bytesConst(tint_bytes)));
    blue.kind.uint.store(blue.bytes(tint_bytes), 200);
    try testing.expectEqual(@as(u8, 200), v.tint.b);
    try testing.expectEqual(@as(u8, 2), v.tint.g);
}

test "reflect - descriptor identity" {
    const T = struct { x: f32 };
    try testing.expectEqual(describe(T), describe(T));

    const again = struct {
        fn get() *const TypeDescriptor {
            return describe(T);
        }
    }.get();
    try testing.expectEqual(describe(T), again);
}

test "reflect - packed and non-struct" {
    const Packed = packed struct { a: u3, b: u5 };
    const packed_desc = describe(Packed);
    try testing.expectEqual(@as(?Reason, .packed_layout), packed_desc.unwalkable);
    try testing.expectEqual(@as(usize, 0), packed_desc.fields.len);

    // A packed struct nested in a normal one is reported per-field instead.
    const Outer = struct { flags: Packed };
    try testing.expectEqual(Reason.packed_layout, describe(Outer).fields[0].kind.unsupported.reason);

    // Non-struct components get one synthetic field so they stay editable.
    const int_desc = describe(u32);
    try testing.expectEqual(@as(?Reason, .not_a_struct), int_desc.unwalkable);
    try testing.expectEqual(@as(usize, 1), int_desc.fields.len);
    try testing.expectEqualStrings("value", int_desc.fields[0].name);

    var n: u32 = 5;
    const bytes = std.mem.asBytes(&n)[0..];
    int_desc.fields[0].kind.uint.store(bytes, 11);
    try testing.expectEqual(@as(u32, 11), n);
}

